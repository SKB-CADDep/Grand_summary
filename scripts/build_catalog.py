def _column_key(label: str) -> str:
    text = label.strip()
    if text.endswith("ПКУ"):
        return f"pku_{text.split()[0]}"
    if text.endswith("ЗКУ"):
        return f"zku_{text.split()[0]}"
    match = re.fullmatch(r"(\d+)\s*\((\d+)\)", text)
    if match:
        return f"s{match.group(1)}_{match.group(2)}"
    return f"s{text}"


def _column_kind(label: str) -> str:
    text = label.strip()
    if text.endswith("ПКУ"):
        return "pku"
    if text.endswith("ЗКУ"):
        return "zku"
    return "stage"


def _indent_level(label: str) -> int:
    spaces = len(label) - len(label.lstrip(" "))
    return spaces // 5


def _unit(label: str) -> str | None:
    stripped = label.strip().rstrip(":")
    match = re.search(r",\s*([^,]+)$", stripped)
    if not match:
        return None
    unit = match.group(1).strip()
    if unit.lower() in {"да/нет"}:
        return None
    if "(" in unit or ")" in unit or len(unit) > 16:
        return None
    return unit


def build_catalog() -> dict:
    columns = [
        {
            "key": _column_key(label),
            "label": label,
            "kind": _column_kind(label),
            "order": index,
        }
        for index, label in enumerate(COLUMN_LABELS)
    ]

    levels = [_indent_level(label) for _, label in TEMPLATE_ROWS]
    parameters: list[dict] = []
    current_group = "flow_path"
    group_by_level: dict[int, str] = {0: "flow_path"}

    for index, ((row, label), level) in enumerate(zip(TEMPLATE_ROWS, levels)):
        next_level = levels[index + 1] if index + 1 < len(levels) else level
        is_section = level == 0 or next_level > level
        stripped = label.strip()
        if is_section:
            current_group = f"r{row:03d}"
            group_by_level[level] = current_group
        else:
            parent_level = max((lv for lv in group_by_level if lv < level), default=0)
            current_group = group_by_level.get(parent_level, current_group)

        parameters.append(
            {
                "key": f"r{row:03d}",
                "excel_row": row,
                "label": stripped,
                "label_raw": label,
                "group": current_group if not is_section else current_group,
                "indent": level,
                "row_kind": "section" if is_section else "editable",
                "unit": None if is_section else _unit(label),
                "order": index,
            }
        )

    return {
        "template": "default.XLS",
        "sheet_hint": "шаблон гранд-сводки",
        "header_rows": [1, 2, 3],
        "columns": columns,
        "parameters": parameters,
    }


def main() -> None:
    catalog = build_catalog()
    out_dir = templates_dir()
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "parameter_catalog.json"
    path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2), encoding="utf-8")
    params = catalog["parameters"]
    sections = sum(1 for item in params if item["row_kind"] == "section")
    print(f"Wrote {path} ({len(params)} rows, {sections} sections, {len(catalog['columns'])} columns)")


if __name__ == "__main__":
    main()
